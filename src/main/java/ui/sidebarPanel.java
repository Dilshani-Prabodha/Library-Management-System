public void setActiveButton(String activePage) {

    java.awt.Color normalColor =
            new java.awt.Color(15, 35, 75);

    java.awt.Color activeColor =
            new java.awt.Color(40, 120, 208);

    btnDashboard.setBackground(normalColor);
    btnBooks.setBackground(normalColor);
    btnMembers.setBackground(normalColor);
    btnBorrowBooks.setBackground(normalColor);
    btnReturnBooks.setBackground(normalColor);

    btnDashboard.setForeground(java.awt.Color.WHITE);
    btnBooks.setForeground(java.awt.Color.WHITE);
    btnMembers.setForeground(java.awt.Color.WHITE);
    btnBorrowBooks.setForeground(java.awt.Color.WHITE);
    btnReturnBooks.setForeground(java.awt.Color.WHITE);

    switch (activePage) {
        case "DASHBOARD":
            btnDashboard.setBackground(activeColor);
            break;

        case "BOOKS":
            btnBooks.setBackground(activeColor);
            break;

        case "MEMBERS":
            btnMembers.setBackground(activeColor);
            break;

        case "BORROW":
            btnBorrowBooks.setBackground(activeColor);
            break;

        case "RETURN":
            btnReturnBooks.setBackground(activeColor);
            break;
    }
}

