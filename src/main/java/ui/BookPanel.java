    private void loadBooks() {
    DefaultTableModel model =
        (DefaultTableModel) tblBookDetails.getModel();

    model.setRowCount(0);

    ArrayList<Book> books = bookService.getAllBooks();

    for (Book book : books) {
        model.addRow(new Object[] {
            book.getBookId(),
            book.getTitle(),
            book.getAuthor(),
            book.getCategory(),
            book.getStatus()
        });
    }
}
    
    private void addBook() {

    String bookId = txtBookId.getText().trim();
    String title = txtBookTitle.getText().trim();
    String author = txtAuthor.getText().trim();
    String category = (String) cmbCategory.getSelectedItem();

    Book book = new Book(
        bookId,
        title,
        author,
        category,
        "Available"
    );

    String message = bookService.addBook(book);

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Book added successfully.")) {
        loadBooks();
        clearForm();
    }
}
    
    private void clearForm() {
    txtBookId.setText("");
    txtBookTitle.setText("");
    txtAuthor.setText("");

    if (cmbCategory.getItemCount() > 0) {
        cmbCategory.setSelectedIndex(0);
    }

    txtBookId.requestFocusInWindow();
}
    
    private void searchBooks() {

    String keyword = txtBookSearchBar.getText().trim();

    DefaultTableModel model =
        (DefaultTableModel) tblBookDetails.getModel();

    model.setRowCount(0);

    ArrayList<Book> books = bookService.searchBooks(keyword);

    for (Book book : books) {
        model.addRow(new Object[] {
            book.getBookId(),
            book.getTitle(),
            book.getAuthor(),
            book.getCategory(),
            book.getStatus()
        });
    }

    if (books.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "No matching books found."
        );
    }
}
    
private void deleteSelectedBook() {

    int selectedRow = tblBookDetails.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select a book from the table."
        );
        return;
    }

    String bookId = tblBookDetails
        .getValueAt(selectedRow, 0)
        .toString();

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete book " + bookId + "?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String message = bookService.deleteBook(bookId);

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Book deleted successfully.")) {
        loadBooks();
        clearForm();
    }
}

public void refreshData() {
    loadBooks();
}

