    public LibraryDashboardFrame() {
        initComponents();
        
        getContentPane().remove(sidebarPlaceholder);
        getContentPane().remove(contentPanelHolder);

        sidebarPanel sidePanel = new sidebarPanel();
        
        sidePanel.setActiveButton("DASHBOARD");
        
        sidePanel.setDashboardAction(e -> {
            sidePanel.setActiveButton("DASHBOARD");
            dashboardPanel.refreshDashboard();
            cardLayout.show(cardPanel, "DASHBOARD");
        });
        
        sidePanel.setBooksAction(e -> {
            sidePanel.setActiveButton("BOOKS");
            bookPanel.refreshData();
            cardLayout.show(cardPanel, "BOOKS");
        });
        
        sidePanel.setMembersAction(e -> {
            sidePanel.setActiveButton("MEMBERS");
            cardLayout.show(cardPanel, "MEMBERS");
        });

        sidePanel.setBorrowBooksAction(e -> {
            sidePanel.setActiveButton("BORROW");
            cardLayout.show(cardPanel, "BORROW");
            borrowBookPanel.refreshData();
        });
       
        sidePanel.setReturnBooksAction(e -> {
            sidePanel.setActiveButton("RETURN");
            cardLayout.show(cardPanel, "RETURN");
            returnBookPanel.refreshData();
        });
        
        sidePanel.setExitAction(e -> {
            int choice = javax.swing.JOptionPane.showConfirmDialog(
             this,
                "Are you sure you want to exit the Library Management System?",
                "Confirm Exit",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (choice == javax.swing.JOptionPane.YES_OPTION) {
                System.exit(0);
            }
        });

        
        mainPanel = new contentPanel();
        cardLayout = new java.awt.CardLayout();
        cardPanel = new javax.swing.JPanel(cardLayout);
        dashboardPanel = new DashboardPanel();
        bookPanel = new BookPanel();
        memberPanel = new MemberPanel();
        borrowBookPanel = new BorrowBookPanel();
        returnBookPanel = new ReturnBookPanel();

        cardPanel.add(dashboardPanel, "DASHBOARD");
        cardPanel.add(bookPanel, "BOOKS");
        cardPanel.add(memberPanel, "MEMBERS");
        cardPanel.add(borrowBookPanel, "BORROW");
        cardPanel.add(returnBookPanel, "RETURN");
        
        cardLayout.show(cardPanel, "DASHBOARD");
        
        
        dashboardPanel.setAddBooksAction(e -> {
            sidePanel.setActiveButton("BOOKS");
            bookPanel.refreshData();
            cardLayout.show(cardPanel, "BOOKS");
        });

        dashboardPanel.setAddMembersAction(e -> {
            sidePanel.setActiveButton("MEMBERS");
            cardLayout.show(cardPanel, "MEMBERS");
        });

        dashboardPanel.setBorrowBooksAction(e -> {
            sidePanel.setActiveButton("BORROW");
            borrowBookPanel.refreshData();
            cardLayout.show(cardPanel, "BORROW");
        });

        dashboardPanel.setReturnBooksAction(e -> {
            sidePanel.setActiveButton("RETURN");
            returnBookPanel.refreshData();
            cardLayout.show(cardPanel, "RETURN");
        });

        getContentPane().add(sidePanel, java.awt.BorderLayout.WEST);
        getContentPane().add(cardPanel, java.awt.BorderLayout.CENTER);

        revalidate();
        repaint();
        
        setTitle("Library Management System");
        setLocationRelativeTo(null);
        setDefaultCloseOperation(javax.swing.JFrame.EXIT_ON_CLOSE);
         
    }

    
