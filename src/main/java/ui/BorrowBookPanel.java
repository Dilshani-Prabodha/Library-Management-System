    private void displaySelectedBook() {

    int index = cmbAvailableBooks.getSelectedIndex();

    if (index <= 0) {
        lblBookIDValue.setText("-");
        lblTitleValue.setText("-");
        lblAuthorValue.setText("-");
        lblCategoryValue.setText("-");
        lblStatusValue.setText("-");
        return;
    }

    Book book = availableBooks.get(index - 1);

    lblBookIDValue.setText(book.getBookId());
    lblTitleValue.setText(book.getTitle());
    lblAuthorValue.setText(book.getAuthor());
    lblCategoryValue.setText(book.getCategory());
    lblStatusValue.setText(book.getStatus());
}
    
    
private void borrowSelectedBook() {

    // Check whether a member has been selected
    int memberIndex = cmbMember.getSelectedIndex();

    if (memberIndex <= 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a member."
        );
        return;
    }

    // Check whether a book has been selected
    int bookIndex = cmbAvailableBooks.getSelectedIndex();

    if (bookIndex <= 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select an available book."
        );
        return;
    }

    // Get the selected member and book
    Member selectedMember = members.get(memberIndex - 1);
    Book selectedBook = availableBooks.get(bookIndex - 1);

    String message = borrowService.borrowBook(
            selectedBook.getBookId(),
            selectedMember.getMemberId()
    );

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Book borrowed successfully.")) {

        loadAvailableBooks();

        lblBookIDValue.setText("-");
        lblTitleValue.setText("-");
        lblAuthorValue.setText("-");
        lblCategoryValue.setText("-");
        lblStatusValue.setText("-");

        cmbMember.setSelectedIndex(0);
        cmbAvailableBooks.setSelectedIndex(0);
    }
}

    

    private void loadMembers() {

    members = memberDAO.getAllMembers();

    cmbMember.removeAllItems();
    cmbMember.addItem("-- Select Member --");

    for (Member member : members) {
        cmbMember.addItem(
                member.getMemberId() + " - " + member.getName()
        );
    }
}
    
    private void loadAvailableBooks() {

    availableBooks = borrowService.getAvailableBooks();

    cmbAvailableBooks.removeAllItems();
    cmbAvailableBooks.addItem("-- Select Book --");

    for (Book book : availableBooks) {
        cmbAvailableBooks.addItem(
                book.getBookId() + " - " + book.getTitle()
        );
    }
}
