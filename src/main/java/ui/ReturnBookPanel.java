    private void btnReturnBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReturnBookActionPerformed
            int index = cmbBorrowedBooks.getSelectedIndex();

    if (index <= 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a borrowed book."
        );
        return;
    }

    BorrowRecord selectedRecord =
            activeBorrowRecords.get(index - 1);

    String bookId =
            selectedRecord.getBook().getBookId();

    String message = borrowService.returnBook(bookId);

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Book returned successfully.")) {

        loadActiveBorrowRecords();

        cmbBorrowedBooks.setSelectedIndex(0);

        clearBookDetails();
    }
    }//GEN-LAST:event_btnReturnBookActionPerformed

    public void refreshData() {
    loadActiveBorrowRecords();
}

