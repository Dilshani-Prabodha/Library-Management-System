    private void loadActiveBorrowRecords() {

    activeBorrowRecords = borrowService.getActiveBorrowRecords();

    cmbBorrowedBooks.removeAllItems();

    cmbBorrowedBooks.addItem("-- Select Borrowed Book --");

    for (BorrowRecord record : activeBorrowRecords) {

        String bookDetails =
                record.getBook().getBookId()
                + " - "
                + record.getBook().getTitle();

        cmbBorrowedBooks.addItem(bookDetails);
    }

    clearBookDetails();
}
    private void displaySelectedBorrowRecord() {

    int index = cmbBorrowedBooks.getSelectedIndex();

    if (index <= 0) {
        clearBookDetails();
        return;
    }

    BorrowRecord record = activeBorrowRecords.get(index - 1);

    lblRBookIDValue.setText(
            record.getBook().getBookId()
    );

    lblRTitleValue.setText(
            record.getBook().getTitle()
    );

    // Display both Member ID and Member Name
    lblRMemberValue.setText(
            record.getMember().getMemberId()
            + " - "
            + record.getMember().getName()
    );

    lblRBorrowDateValue.setText(
            record.getBorrowDate().toString()
    );

    lblRStatusValue.setText(
            record.getStatus()
    );
}
    
    private void clearBookDetails() {

    lblRBookIDValue.setText("-");
    lblRTitleValue.setText("-");
    lblRMemberValue.setText("-");
    lblRBorrowDateValue.setText("-");
    lblRStatusValue.setText("-");
}
