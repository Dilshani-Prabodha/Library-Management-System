    private void loadMembers() {
    DefaultTableModel model =
            (DefaultTableModel) tblMemDetails.getModel();

    model.setRowCount(0);

    ArrayList<Member> members = memberService.getAllMembers();

    for (Member member : members) {
        model.addRow(new Object[] {
            member.getMemberId(),
            member.getName(),
            member.getContactNumber()
        });
    }
}
    
    private void addMember() {

    String id = txtMemID.getText().trim();
    String name = txtMemName.getText().trim();
    String contact = txtContact.getText().trim();

    Member member = new Member(id, name, contact);

    String message = memberService.addMember(member);

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Member added successfully.")) {
        loadMembers();
        clearForm();
    }
}
    
    private void clearForm() {

    txtMemID.setText("");
    txtMemName.setText("");
    txtContact.setText("");
    txtMemSearchBar.setText("");

    txtMemID.setEditable(true);

    tblMemDetails.clearSelection();

    txtMemID.requestFocusInWindow();
}
    
    private void searchMembers() {

    String keyword = txtMemSearchBar.getText().trim();

    ArrayList<Member> members =
            memberService.searchMembers(keyword);

    DefaultTableModel model =
            (DefaultTableModel) tblMemDetails.getModel();

    model.setRowCount(0);

    for (Member member : members) {

        model.addRow(new Object[]{
            member.getMemberId(),
            member.getName(),
            member.getContactNumber()
        });
    }

    if (members.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "No matching members found."
        );
    }
}
    
    private void updateMember() {

    String id = txtMemID.getText().trim();
    String name = txtMemName.getText().trim();
    String contact = txtContact.getText().trim();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a member to update."
        );
        return;
    }

    Member member = new Member(id, name, contact);

    String message = memberService.updateMember(member);

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Member updated successfully.")) {
        loadMembers();
        clearForm();
    }
}
    
    
private void deleteMember() {

    String id = txtMemID.getText().trim();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a member to delete."
        );
        return;
    }

    int choice = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete member " + id + "?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (choice != JOptionPane.YES_OPTION) {
        return;
    }

    String message = memberService.deleteMember(id);

    JOptionPane.showMessageDialog(this, message);

    if (message.equals("Member deleted successfully.")) {
        loadMembers();
        clearForm();
    }
}

